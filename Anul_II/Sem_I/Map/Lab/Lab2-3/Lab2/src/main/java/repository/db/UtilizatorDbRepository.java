package repository.db;

import domain.Utilizator;
import domain.validators.ValidationException;
import domain.validators.Validator;
import repository.Repository;
import repository.RepositoryException;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

/**
 * database repo for users, every operation is a query on the table users(id, first_name, last_name)
 * Nothing is kept in memory; the id of a new user is generated by the database
 */
public class UtilizatorDbRepository implements Repository<Long, Utilizator> {

    private final Validator<Utilizator> validator;
    private final String url;
    private final String user;
    private final String password;

    /**
     * @param validator the validation strategy for users
     * @param url database url
     * @param user database user
     * @param password the password
     */
    public UtilizatorDbRepository(Validator<Utilizator> validator, String url, String user, String password) {
        this.validator = validator;
        this.url = url;
        this.user = user;
        this.password = password;
    }

    /**
     * @param id entity that must be returned, not null
     * @return the user with that id, null if it doesn't exist
     * @throws IllegalArgumentException if id is null
     * @throws RepositoryException if the database cannot be accessed
     */
    @Override
    public Utilizator findOne(Long id) {
        if (id == null)
            throw new IllegalArgumentException("id-ul nu poate fi null!");
        // * conexiunea, instructiunea si ResultSet-ul se inchid singure (try-with-resources)
        // * ? = parametru: valoarea se trimite separat de textul SQL, deci nu poate deveni cod SQL
        try (Connection connection = DriverManager.getConnection(url, user, password);
             PreparedStatement ps = connection.prepareStatement("SELECT * FROM users WHERE id = ?")) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                // * cursorul porneste inaintea primului rand; next() = false daca nu exista niciun rand
                if (rs.next())
                    return dinRand(rs);
                return null;
            }
        } catch (SQLException e) {
            // * SQLException e checked: o impachetam in RepositoryException (unchecked), ca Repository sa nu depinda de JDBC
            throw new RepositoryException("Eroare la findOne: " + e.getMessage(), e);
        }
    }

    /**
     * @return all the users, ordered by id
     * @throws RepositoryException if the database cannot be accessed
     */
    @Override
    public Iterable<Utilizator> findAll() {
        List<Utilizator> users = new ArrayList<>();
        try (Connection connection = DriverManager.getConnection(url, user, password);
             PreparedStatement ps = connection.prepareStatement("SELECT * FROM users ORDER BY id");
             ResultSet rs = ps.executeQuery()) {
            // * ResultSet nu e o colectie si nu are stream(): se parcurge rand cu rand cu while (ca la curs)
            while (rs.next())
                users.add(dinRand(rs));
        } catch (SQLException e) {
            throw new RepositoryException("Eroare la findAll: " + e.getMessage(), e);
        }
        return users;
    }

    /**
     * Saves the user; the id is generated by the database and set on the entity
     *
     * @param entity the user that must be saved, not null; its id is ignored
     * @return null, the user is saved (with the generated id)
     * @throws IllegalArgumentException if the entity is null
     * @throws ValidationException if the entity is not valid
     * @throws RepositoryException if the database cannot be accessed
     */
    @Override
    public Utilizator save(Utilizator entity) {
        if (entity == null)
            throw new IllegalArgumentException("entitatea nu poate fi null!");
        validator.validate(entity);
        // * fara id in INSERT: il genereaza baza de date (GENERATED ALWAYS AS IDENTITY)
        String sql = "INSERT INTO users (first_name, last_name) VALUES (?, ?)";
        // * RETURN_GENERATED_KEYS: dupa INSERT putem cere randul inserat, cu id-ul generat
        try (Connection connection = DriverManager.getConnection(url, user, password);
             PreparedStatement ps = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, entity.getFirstName());
            ps.setString(2, entity.getLastName());
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                keys.next();
                // * id-ul primit de la baza de date ajunge pe obiect, deci service-ul si UI-ul il vad
                entity.setId(keys.getLong("id"));
            }
        } catch (SQLException e) {
            throw new RepositoryException("Eroare la save: " + e.getMessage(), e);
        }
        return null;
    }

    /**
     * @param id entity that must be deleted, not null
     * @return the deleted user, null if there is no user with that id
     * @throws IllegalArgumentException if id is null
     * @throws RepositoryException if the database cannot be accessed
     */
    @Override
    public Utilizator delete(Long id) {
        // * intai il cautam: trebuie sa intoarcem utilizatorul sters (findOne arunca si IAE pt id null)
        Utilizator gasit = findOne(id);
        if (gasit == null)
            return null;
        try (Connection connection = DriverManager.getConnection(url, user, password);
             PreparedStatement ps = connection.prepareStatement("DELETE FROM users WHERE id = ?")) {
            ps.setLong(1, id);
            ps.executeUpdate();
        } catch (SQLException e) {
            throw new RepositoryException("Eroare la delete: " + e.getMessage(), e);
        }
        return gasit;
    }

    /**
     * @param entity the user with the new data, not null
     * @return null if the user was updated, otherwise, the user (if it doesn't exist)
     * @throws IllegalArgumentException if the entity is null
     * @throws ValidationException if the entity is not valid
     * @throws RepositoryException if the database cannot be accessed
     */
    @Override
    public Utilizator update(Utilizator entity) {
        if (entity == null)
            throw new IllegalArgumentException("entitatea nu poate fi null!");
        validator.validate(entity);
        String sql = "UPDATE users SET first_name = ?, last_name = ? WHERE id = ?";
        try (Connection connection = DriverManager.getConnection(url, user, password);
             PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, entity.getFirstName());
            ps.setString(2, entity.getLastName());
            ps.setLong(3, entity.getId());
            // * executeUpdate intoarce cate randuri s-au modificat: 0 = nu exista utilizatorul cu id-ul acesta
            int randuri = ps.executeUpdate();
            return randuri == 0 ? entity : null;
        } catch (SQLException e) {
            throw new RepositoryException("Eroare la update: " + e.getMessage(), e);
        }
    }

    /**
     * Creates a user from the current row of a query on the table users
     *
     * @param rs a ResultSet positioned on a row
     * @return the user described by the row
     * @throws SQLException if a column doesn't exist
     */
    private static Utilizator dinRand(ResultSet rs) throws SQLException {
        // * un rand din tabel devine un Utilizator (scris o singura data, folosit de findOne si findAll)
        Utilizator u = new Utilizator(rs.getString("first_name"), rs.getString("last_name"));
        u.setId(rs.getLong("id"));
        return u;
    }
}
